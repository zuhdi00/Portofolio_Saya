/* ---------------------------------------------------------------------------
   STEP 3 — TABEL PENYESUAIAN (snapshot, dihitung sekali di cut-off)
   nAdjust disimpan sebagai angka tetap supaya stok tidak bergeser sendiri
   kalau ada perubahan data historis di belakang.
   --------------------------------------------------------------------------- */
CREATE TABLE dbo.tbStokGudangAdj (
    cNoSc       VARCHAR(20) NOT NULL,
    dCutOff     DATE        NOT NULL,
    nStbDb      INT         NOT NULL DEFAULT 0,   -- SUM tbStbBJ.nQty
    nDtStockDb  INT         NOT NULL DEFAULT 0,   -- SUM tbDtStockDtl.nStock (saat cut-off)
    nReturDb    INT         NOT NULL DEFAULT 0,
    nKirimDb    INT         NOT NULL DEFAULT 0,
    nStokTarget INT         NOT NULL DEFAULT 0,   -- angka Excel
    nAdjust     INT         NOT NULL DEFAULT 0,   -- selisih yang dikurangkan
    dHitung     DATETIME    NOT NULL DEFAULT GETDATE(),
    UserId      VARCHAR(30) NULL,
    CONSTRAINT PK_tbStokGudangAdj PRIMARY KEY (cNoSc)
);
GO

DECLARE @CutOff DATE = '2026-08-03';

BEGIN TRY
    BEGIN TRANSACTION;

    -- 3a. PENGAMAN: batalkan kalau sudah ada transaksi setelah cut-off,
    --     karena angka Excel belum mencakup transaksi tersebut.
    IF EXISTS (SELECT 1 FROM dbo.tbStbBJ s
               INNER JOIN dbo.tbStokGudangExcel e ON e.cNoSc = s.cNoSc
               WHERE CONVERT(date, s.dTanggal) > @CutOff)
        THROW 50001, 'DIBATALKAN: ada STB bertanggal setelah 03 Agu 2026. Update file Excel sampai tanggal terakhir, lalu ulangi.', 1;

    IF EXISTS (SELECT 1 FROM dbo.tbSRJ s
               INNER JOIN dbo.tbSRJDtl d ON d.cNoSRJ = s.cNoSRJ
               INNER JOIN dbo.tbStokGudangExcel e ON e.cNoSc = COALESCE(d.cNoScDtl, s.cNoSC)
               WHERE CONVERT(date, s.dTanggal) > @CutOff)
        THROW 50002, 'DIBATALKAN: ada Surat Jalan bertanggal setelah 03 Agu 2026. Update file Excel sampai tanggal terakhir, lalu ulangi.', 1;

    -- 3b. Hitung dan simpan penyesuaian
    ;WITH db_stok AS (
        SELECT x.cNoSc,
               SUM(x.stb) AS stb, SUM(x.dtstock) AS dtstock,
               SUM(x.retur) AS retur, SUM(x.kirim) AS kirim
        FROM (
            SELECT cNoSc, SUM(nQty) AS stb, 0 AS dtstock, 0 AS retur, 0 AS kirim
            FROM dbo.tbStbBJ GROUP BY cNoSc
            UNION ALL
            SELECT cNoSc, 0, SUM(ISNULL(nStock,0)), 0, 0
            FROM dbo.tbDtStockDtl GROUP BY cNoSc
            UNION ALL
            SELECT COALESCE(d.cNoScDtl, s.cNoSC), 0, 0, SUM(rv.nQty), 0
            FROM dbo.vwReturnSrj rv
            INNER JOIN dbo.tbSRJDtl d ON d.cNoSRJ = rv.cNoSrj
            INNER JOIN dbo.tbSRJ    s ON s.cNoSRJ = d.cNoSRJ
            GROUP BY COALESCE(d.cNoScDtl, s.cNoSC)
            UNION ALL
            SELECT COALESCE(d.cNoScDtl, s.cNoSC), 0, 0, 0, SUM(d.nQty)
            FROM dbo.tbSRJ s
            INNER JOIN dbo.tbSRJDtl d ON s.cNoSRJ = d.cNoSRJ
            GROUP BY COALESCE(d.cNoScDtl, s.cNoSC)
        ) x
        GROUP BY x.cNoSc
    )
    INSERT INTO dbo.tbStokGudangAdj
          (cNoSc, dCutOff, nStbDb, nDtStockDb, nReturDb, nKirimDb, nStokTarget, nAdjust, UserId)
    SELECT e.cNoSc, @CutOff,
           ISNULL(d.stb,0), ISNULL(d.dtstock,0), ISNULL(d.retur,0), ISNULL(d.kirim,0),
           e.nStokAkhirPc,
           ISNULL(d.stb,0) - ISNULL(d.dtstock,0) + ISNULL(d.retur,0) - ISNULL(d.kirim,0) - e.nStokAkhirPc,
           SUSER_SNAME()
    FROM       dbo.tbStokGudangExcel e
    LEFT JOIN  db_stok d ON d.cNoSc = e.cNoSc;

    COMMIT TRANSACTION;
    PRINT 'OK — tabel penyesuaian berhasil dibuat. Lanjut STEP 4 & 5.';
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
    SELECT ERROR_NUMBER() AS err_no, ERROR_MESSAGE() AS err_msg;
END CATCH
GO

/* ---------------------------------------------------------------------------
   STEP 4 — VIEW STOK FINAL + VERIFIKASI
   --------------------------------------------------------------------------- */
CREATE VIEW dbo.vwStokBJFinal AS
WITH db_stok AS (
    SELECT x.cNoSc,
           SUM(x.stb) AS stb, SUM(x.dtstock) AS dtstock,
           SUM(x.retur) AS retur, SUM(x.kirim) AS kirim
    FROM (
        SELECT cNoSc, SUM(nQty) AS stb, 0 AS dtstock, 0 AS retur, 0 AS kirim
        FROM dbo.tbStbBJ GROUP BY cNoSc
        UNION ALL
        SELECT cNoSc, 0, SUM(ISNULL(nStock,0)), 0, 0
        FROM dbo.tbDtStockDtl GROUP BY cNoSc
        UNION ALL
        SELECT COALESCE(d.cNoScDtl, s.cNoSC), 0, 0, SUM(rv.nQty), 0
        FROM dbo.vwReturnSrj rv
        INNER JOIN dbo.tbSRJDtl d ON d.cNoSRJ = rv.cNoSrj
        INNER JOIN dbo.tbSRJ    s ON s.cNoSRJ = d.cNoSRJ
        GROUP BY COALESCE(d.cNoScDtl, s.cNoSC)
        UNION ALL
        SELECT COALESCE(d.cNoScDtl, s.cNoSC), 0, 0, 0, SUM(d.nQty)
        FROM dbo.tbSRJ s
        INNER JOIN dbo.tbSRJDtl d ON s.cNoSRJ = d.cNoSRJ
        GROUP BY COALESCE(d.cNoScDtl, s.cNoSC)
    ) x
    GROUP BY x.cNoSc
)
SELECT  d.cNoSc,
        ISNULL(d.stb,0)                     AS total_stb,
        ISNULL(d.dtstock,0)                 AS total_dtstock,
        ISNULL(a.nAdjust,0)                 AS total_adjust,
        ISNULL(d.retur,0)                   AS total_retur,
        ISNULL(d.kirim,0)                   AS total_kirim,
        ISNULL(d.stb,0) - ISNULL(d.dtstock,0) - ISNULL(a.nAdjust,0)
            + ISNULL(d.retur,0) - ISNULL(d.kirim,0)  AS sisa_stb,
        e.nStokAkhirPc                      AS stok_excel,
        e.cKeterangan
FROM       db_stok d
LEFT JOIN  dbo.tbStokGudangAdj   a ON a.cNoSc = d.cNoSc
LEFT JOIN  dbo.tbStokGudangExcel e ON e.cNoSc = d.cNoSc;
GO

-- VERIFIKASI 1 — HARUS 0 BARIS
SELECT * FROM dbo.vwStokBJFinal
WHERE  stok_excel IS NOT NULL AND sisa_stb <> stok_excel;

-- VERIFIKASI 2 — kedua kolom HARUS 776500
SELECT SUM(sisa_stb) AS total_sistem, SUM(stok_excel) AS total_excel
FROM   dbo.vwStokBJFinal WHERE stok_excel IS NOT NULL;
